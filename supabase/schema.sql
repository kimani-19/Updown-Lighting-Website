create table if not exists public.quote_requests (
  id bigint generated by default as identity primary key,
  full_name text not null,
  email_address text not null,
  phone_number text not null,
  property_address text not null,
  service_type text not null,
  additional_details text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  subject text,
  message text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.gallery_images (
  id bigint generated by default as identity primary key,
  title text,
  description text,
  image_url text not null,
  category text,
  storage_path text,
  poster_url text,
  media_type text not null default 'image',
  created_at timestamptz not null default now()
);

alter table public.quote_requests enable row level security;
alter table public.contact_messages enable row level security;
alter table public.gallery_images enable row level security;

-- Public quote and contact submissions
create policy "Public quote submissions"
  on public.quote_requests
  for insert
  to anon, authenticated
  with check (true);

create policy "Public contact submissions"
  on public.contact_messages
  for insert
  to anon, authenticated
  with check (true);

-- Public gallery reads
create policy "Public gallery reads"
  on public.gallery_images
  for select
  to anon, authenticated
  using (true);

-- Admin-only reads and management
create policy "Admin quote reads"
  on public.quote_requests
  for select
  to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

create policy "Admin contact reads"
  on public.contact_messages
  for select
  to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

create policy "Admin gallery writes"
  on public.gallery_images
  for all
  to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
  with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');
